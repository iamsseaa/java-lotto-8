package lotto;

public enum Rank {
    FIRST,
    SECOND,
    THIRD,
    FOURTH,
    FIFTH,
    MISS;

    public static Rank valueOf(long matchCount, boolean hasBonus) {
        if (matchCount == 6) {
            return FIRST;
        }
        if (matchCount == 5 && hasBonus) {
            return SECOND;
        }
        if (matchCount == 5) {
            return THIRD;
        }
        if (matchCount == 4) {
            return FOURTH;
        }
        if (matchCount == 3) {
            return FIFTH;
        }
        return MISS;
    }
}
